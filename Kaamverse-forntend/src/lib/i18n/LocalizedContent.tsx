const wordPattern = new RegExp(`\\b(${Object.keys(wordTranslations).sort((a, b) => b.length - a.length).join('|')})\\b`, 'gi')

function translateValue(value: string) {
  const match = value.match(/^(\s*)(.*?)(\s*)$/s)
  if (!match) return value
  const [, before, content, after] = match
  if (!content) return value
  let translated = translations[content] || content
  if (translated === content) {
    for (const [pattern, replacement] of phraseTranslations) translated = translated.replace(pattern, replacement)
  }
  translated = translated.replace(wordPattern, word => wordTranslations[word.toLowerCase()] || word)
  return `${before}${translated}${after}`
}

const originalText = new WeakMap<Text, string>()
const translatedText = new WeakMap<Text, string>()
const originalAttributes = new WeakMap<HTMLElement, Map<string, string>>()
const translatedAttributeValues = new WeakMap<HTMLElement, Map<string, string>>()
const translatedAttributes = ['placeholder', 'title', 'aria-label'] as const

function localizeNode(root: HTMLElement, language: AppLanguage) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode() as Text | null
  while (node) {
    const parent = node.parentElement
    if (parent && !['SCRIPT', 'STYLE'].includes(parent.tagName)) {
      const previousTranslation = translatedText.get(node)
      if (!originalText.has(node) || (previousTranslation !== undefined && node.data !== previousTranslation)) originalText.set(node, node.data)
      const original = originalText.get(node) ?? node.data
      const next = language === 'np' ? translateValue(original) : original
      if (node.data !== next) node.data = next
      translatedText.set(node, next)
    }
    node = walker.nextNode() as Text | null
  }

  for (const element of [root, ...Array.from(root.querySelectorAll<HTMLElement>('*'))]) {
    let originals = originalAttributes.get(element)
    let previousTranslations = translatedAttributeValues.get(element)
    if (!originals) { originals = new Map(); originalAttributes.set(element, originals) }
    if (!previousTranslations) { previousTranslations = new Map(); translatedAttributeValues.set(element, previousTranslations) }
    for (const attribute of translatedAttributes) {
      const value = element.getAttribute(attribute)
      if (value === null) continue
      const previousTranslation = previousTranslations.get(attribute)
      if (!originals.has(attribute) || (previousTranslation !== undefined && value !== previousTranslation)) originals.set(attribute, value)
      const original = originals.get(attribute) || value
      const next = language === 'np' ? translateValue(original) : original
      if (value !== next) element.setAttribute(attribute, next)
      previousTranslations.set(attribute, next)
    }
  }
}

export function LocalizedContent({ language, children }: { language: AppLanguage; children: ReactNode }) {
  const rootRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    if (!rootRef.current) return
    const root = document.body
    let applying = false
    const apply = () => {
      if (applying) return
      applying = true
      localizeNode(root, language)
      applying = false
    }
    apply()
    const observer = new MutationObserver(() => queueMicrotask(apply))
    observer.observe(root, { subtree: true, childList: true, characterData: true })
    return () => observer.disconnect()
  }, [language])

  return <div ref={rootRef}>{children}</div>
}
